"""
Fake N-BaIoT generator — files in the exact on-disk format of the real dataset,
so the REAL data path (data/load_nbaiot.py) can be exercised end to end without
the UCI download.

Written to data/fake_nbaiot/ (never data/nbaiot/), in the same layout:

    Danmini_Doorbell/benign_traffic.csv
    Danmini_Doorbell/mirai_attacks/scan.csv
    Danmini_Doorbell/gafgyt_attacks/combo.csv
    Ennio_Doorbell/benign_traffic.csv          (second device, Scenario 1)

What is mimicked, because the loader and evidence/featurespace.py depend on it:
  - the 115 real column names, in file order
  - 20 signed columns (HH_*/HpHp_* covariance and pcc), pcc bounded in [-1, 1]
  - dynamic range of ~17 orders of magnitude (HH_jit_*_variance ~ 1e17)
  - attack and second-device benign traffic sit at different operating points

What is NOT mimicked: real temporal structure, real attack semantics, real
inter-feature dependencies beyond one shared per-row factor. Numbers produced
from these files are a plumbing test — never cite them as results.

Usage:
    python data/fake_nbaiot.py [--rows 2500] [--seed 7] [--root data/fake_nbaiot]
"""
import argparse
import os

import numpy as np
import pandas as pd

DEFAULT_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fake_nbaiot")
LAMBDAS = ["L5", "L3", "L1", "L0.1", "L0.01"]
_STATS3 = ["weight", "mean", "variance"]
_STATS7 = ["weight", "mean", "std", "magnitude", "radius", "covariance", "pcc"]
MARKER = "FAKE_DATA.txt"


def feature_names():
    names = []
    for group, stats in [("MI_dir", _STATS3), ("H", _STATS3), ("HH", _STATS7),
                         ("HH_jit", _STATS3), ("HpHp", _STATS7)]:
        for lam in LAMBDAS:
            names.extend(f"{group}_{lam}_{s}" for s in stats)
    return names


def _base_profile(rng):
    """Per-feature (mean, sd) in signed-log space for one benign device."""
    mu, sd = [], []
    for name in feature_names():
        stat = name.rsplit("_", 1)[1]
        if name.startswith("HH_jit") and stat == "variance":
            m = rng.uniform(38.0, 40.0)          # ~1e17, the real outlier columns
        elif name.startswith("HH_jit") and stat == "mean":
            m = rng.uniform(18.0, 21.0)
        elif stat == "weight":
            m = rng.uniform(1.0, 6.0)
        elif stat == "mean":
            m = rng.uniform(4.0, 6.5)
        elif stat == "covariance":
            m = rng.uniform(-3.0, 3.0)
        elif stat == "pcc":
            m = rng.uniform(-0.8, 0.8)           # pre-tanh value
        else:                                    # variance / std / magnitude / radius
            m = rng.uniform(3.0, 10.0)
        mu.append(m)
        sd.append(0.25 if stat == "pcc" else 0.35)
    return np.array(mu), np.array(sd)


def _shift(rng, mu, scale, frac=1.0):
    """Move a profile to a new operating point; `frac` of features move."""
    moved = rng.random(len(mu)) < frac
    delta = rng.normal(scale, 0.3 * abs(scale), len(mu)) * rng.choice([-1, 1], len(mu))
    return mu + np.where(moved, delta, 0.0)


def _sample(rng, mu, sd, n):
    names = feature_names()
    common = rng.normal(0, 1, (n, 1))            # shared per-row load factor
    z = mu + sd * (0.6 * common + 0.8 * rng.normal(0, 1, (n, len(mu))))
    out = np.empty_like(z)
    for j, name in enumerate(names):
        stat = name.rsplit("_", 1)[1]
        if stat == "pcc":
            out[:, j] = np.tanh(z[:, j])
        elif stat == "covariance":
            out[:, j] = np.sign(z[:, j]) * np.expm1(np.abs(z[:, j]))
        else:                                    # non-negative magnitudes
            out[:, j] = np.expm1(np.abs(z[:, j]))
    return pd.DataFrame(out, columns=names)


def generate(root=DEFAULT_ROOT, rows=2500, seed=7):
    rng = np.random.default_rng(seed)
    mu_a, sd = _base_profile(rng)
    profiles = {
        ("Danmini_Doorbell", "benign_traffic.csv"): mu_a,
        ("Danmini_Doorbell", os.path.join("mirai_attacks", "scan.csv")): _shift(rng, mu_a, 2.5),
        ("Danmini_Doorbell", os.path.join("gafgyt_attacks", "combo.csv")): _shift(rng, mu_a, 2.0),
        ("Ennio_Doorbell", "benign_traffic.csv"): _shift(rng, mu_a, 1.2, frac=0.6),
    }
    written = []
    for (device, rel), mu in profiles.items():
        path = os.path.join(root, device, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        _sample(rng, mu, sd, rows).to_csv(path, index=False, float_format="%.8g")
        written.append(path)
    with open(os.path.join(root, MARKER), "w", encoding="utf-8") as f:
        f.write(f"Generated by data/fake_nbaiot.py (rows={rows}, seed={seed}). NOT REAL DATA.\n")
    return written


def ensure(root=DEFAULT_ROOT, **kw):
    """Generate the fake dataset once; later calls are no-ops."""
    if not os.path.exists(os.path.join(root, MARKER)):
        generate(root, **kw)
    return root


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", type=int, default=2500)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--root", default=DEFAULT_ROOT)
    args = ap.parse_args()
    for p in generate(args.root, args.rows, args.seed):
        print("wrote", p)


if __name__ == "__main__":
    main()
